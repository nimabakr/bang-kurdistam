class City {
  const City({
    required this.id,
    required this.kurdishName,
    required this.arabicName,
    required this.englishName,
    required this.governorate,
    this.latitude,
    this.longitude,
    required this.coordinateReference,
  });

  final String id;
  final String kurdishName;
  final String arabicName;
  final String englishName;
  final String governorate;
  final double? latitude;
  final double? longitude;
  final String coordinateReference;

  String get timezone => 'Asia/Baghdad';

  String? get timetableFile => switch (id) {
    'erbil' => 'Hawler.json',
    'sulaymaniyah' => 'Slemany.json',
    'duhok' => 'Duhok.json',
    'halabja' => 'Halabja.json',
    'kalar' => 'Kalar.json',
    'zakho' => 'Zaxo.json',
    'akre' => 'Akre.json',
    'amedi' => 'Amedi.json',
    'ranya' => 'Ranya.json',
    'koya' => 'Koya.json',
    'shaqlawa' => null,
    'chamchamal' => 'Chamchamal.json',
    'penjwen' => 'Penjuin.json',
    'soran' => 'Soran.json',
    'darbandikhan' => 'Darbandixan.json',
    'kifri' => 'Kfri.json',
    'qaladze' => 'Qaladze.json',
    'kirkuk' => 'Kirkuk.json',
    'halabja-nwe' => 'HalabjaN.json',
    'arbat' => 'Arbat.json',
    'piramagrun' => 'Piramagrun.json',
    'tasluja' => 'Tasluja.json',
    'bazyan' => 'Bazyan.json',
    'dukan' => 'Dukan.json',
    'takya' => 'Takya.json',
    'haji-awa' => 'HajiAwa.json',
    'xalakan' => 'Xalakan.json',
    'taq-taq' => 'TaqTaq.json',
    'barznja' => 'Barznja.json',
    'qaradax' => 'Qaradax.json',
    'qadir-karam' => 'QadirKaram.json',
    'xanaqin' => 'Xanaqin.json',
    'chwarta' => 'Chwarta.json',
    'qasre' => 'qasre.json',
    'mosul' => 'mosul.json',
    'tuzxurmatu' => 'tuzxurmatu.json',
    'said-sadiq' => 'SaidSadiq.json',
    _ => null,
  };

  bool matches(String query) {
    final normalized = query.trim().toLowerCase();
    return normalized.isEmpty ||
        kurdishName.toLowerCase().contains(normalized) ||
        arabicName.toLowerCase().contains(normalized) ||
        englishName.toLowerCase().contains(normalized) ||
        governorate.toLowerCase().contains(normalized);
  }
}

